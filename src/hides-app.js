// Each option carries the one direction that answers the question someone
// picked it to ask -- "most remaining" and "largest" are what you look for
// when hunting material, so those run high-to-low, while species and
// thickness read naturally low-to-high.
//
// A hide with no thickness recorded sorts last rather than as zero, which
// would park signature-only hides at the front of the thinnest-first list.
// Sort is stable, so ties keep the server's date order underneath.
const SORTS = {
  added: (a, b) => a.createdAt.localeCompare(b.createdAt),
  remaining: (a, b) => (b.remainingAreaPct ?? 100) - (a.remainingAreaPct ?? 100),
  size: (a, b) => hideFootprintAreaMm2(b) - hideFootprintAreaMm2(a),
  colour: compareByColour,
  species: (a, b) => a.species.localeCompare(b.species),
  thickness: (a, b) => {
    if (a.thicknessMm == null && b.thicknessMm == null) return 0;
    if (a.thicknessMm == null) return 1;
    if (b.thicknessMm == null) return -1;
    return a.thicknessMm - b.thicknessMm;
  },
};

function matchesFilters(hide, query, species) {
  if (species && hide.species.trim().toLowerCase() !== species) return false;
  if (!query) return true;
  const haystack = `${hide.label} ${hide.species} ${hide.id}`.toLowerCase();
  return haystack.includes(query);
}

function renderSpeciesTags() {
  const species = [...new Set(hides.map((h) => h.species.trim().toLowerCase()))].sort();
  speciesTagsEl.innerHTML = species
    .map(
      (s) =>
        `<button type="button" class="tag ${s === selectedSpecies ? 'tag-accent' : 'tag-neutral'}" aria-pressed="${s === selectedSpecies}" data-species="${escapeHtml(s)}">${escapeHtml(s)}</button>`,
    )
    .join('');
}

function renderSummary(visible) {
  const totalAreaMm2 = visible.reduce((sum, h) => sum + hideFootprintAreaMm2(h) * ((h.remainingAreaPct ?? 100) / 100), 0);
  const totalAreaCm2 = Math.round(totalAreaMm2 / 100);
  summaryEl.textContent = `${visible.length} hide${visible.length === 1 ? '' : 's'} · ${totalAreaCm2} cm² usable`;
}

function renderGrid() {
  const query = searchInput.value.trim().toLowerCase();
  const visible = hides
    .filter((h) => matchesFilters(h, query, selectedSpecies))
    .sort(SORTS[sortInput.value] ?? SORTS.added);

  renderSummary(visible);

  gridEl.innerHTML = visible
    .map((hide) => {
      const remaining = hide.remainingAreaPct ?? 100;
      const date = new Date(hide.createdAt).toLocaleDateString();
      const swatch = hide.colourL != null
        ? `<span class="colour-swatch" style="background:${labToCss(hide.colourL, hide.colourA, hide.colourB)}" title="sampled colour"></span>`
        : '';
      // Derived, never stored: a hide is matchable exactly when it carries a
      // scale measurement, which is what the matching page filters on. A
      // separate saved flag could disagree with that, and then one of the two
      // would be lying.
      const matchable = hide.dominantWavelengthMm != null
        ? `<span class="tag tag-accent" title="${hide.dominantWavelengthMm.toFixed(2)}mm scale">matchable</span>`
        : '';
      return `
    <div class="card hide-card elev-sm">
      <img class="washed" src="/skins/${hide.id}/photo" alt="${escapeHtml(hide.label)}" />
      <div class="card-title">
        <span>${escapeHtml(hide.species)} ${swatch}</span>
        <span>${matchable}<span class="tag tag-outline">${hide.id.slice(0, 8)}</span></span>
      </div>
      <p class="card-body">${escapeHtml(hide.label)} · ${hideSizeLabel(hide)}${hide.thicknessMm != null ? ` · ${hide.thicknessMm} mm thick` : ''}${hide.finish ? ` · ${escapeHtml(hide.finish)}` : ''}</p>
      <div class="area-bar"><div class="area-bar-fill" style="width: ${Math.max(0, Math.min(100, remaining))}%"></div></div>
      <div class="card-meta">${Math.round(remaining)}% remaining · captured ${date}</div>
      <div class="card-actions">
        <button type="button" class="btn btn-secondary" data-redigitize="${hide.id}">Update remaining shape</button>
        ${hide.dominantWavelengthMm == null
          ? `<button type="button" class="btn btn-secondary" data-measure="${hide.id}">Measure for matching</button>`
          : ''}
        <button type="button" class="btn btn-secondary" data-delete="${hide.id}">Delete</button>
      </div>
    </div>
  `;
    })
    .join('');
}

async function loadHides() {
  const response = await fetch('/skins');
  hides = await response.json();
  renderSpeciesTags();
  renderGrid();
}

