// species/thickness/finish, each abbreviated to two characters -- the ten
// species on the dropdown all differ in their first two letters, so no
// lookup table is needed, and the same holds for the three finish values.
// Segments for a field not filled in yet are simply omitted, so the name
// builds up as the operator fills the form rather than showing blanks.
function hideNameParts() {
  const parts = [];
  if (speciesInput.value) parts.push(speciesInput.value.slice(0, 2).toUpperCase());
  const thicknessMm = Number(thicknessInput.value);
  if (Number.isFinite(thicknessMm) && thicknessMm > 0) {
    // Tenths of a mm as two digits (1.2mm -> "12") rather than rounding to
    // a whole mm, which would collide constantly -- most of this project's
    // real thicknesses sit between 1.0 and 2.5mm.
    parts.push(String(Math.round(thicknessMm * 10)).padStart(2, '0'));
  }
  if (finishInput.value) parts.push(finishInput.value.slice(0, 2).toUpperCase());
  return parts;
}

// A date fragment beats a bare counter as the tie-breaker: two hides with
// the same species/thickness/finish added on different days are quite
// possibly a different dye lot, which is worth the name saying outright.
// The counter below still exists for the rarer case of two matching that on
// the same day too.
function dateCode() {
  const now = new Date();
  return String(now.getMonth() + 1).padStart(2, '0') + String(now.getDate()).padStart(2, '0');
}

function generateHideName() {
  const parts = hideNameParts();
  if (parts.length === 0) return '';
  parts.push(dateCode());

  const base = parts.join('-');
  const existingLabels = new Set(hides.map((h) => h.label));
  if (!existingLabels.has(base)) return base;
  for (let suffix = 2; ; suffix++) {
    const candidate = `${base}-${suffix}`;
    if (!existingLabels.has(candidate)) return candidate;
  }
}

// Only touches the name field while it still holds what THIS function wrote
// last time (or is empty) -- the moment the operator types their own name
// over it, every later field change leaves it alone.
function maybeAutoGenerateName() {
  if (labelInput.value !== '' && labelInput.value !== lastAutoGeneratedName) return;
  lastAutoGeneratedName = generateHideName();
  labelInput.value = lastAutoGeneratedName;
}

