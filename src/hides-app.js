// Names what is actually about to be destroyed. A confirmation that only
// asks "are you sure?" trains the reflex it is meant to interrupt -- the
// friction has to carry information, or it is just an extra click.
function describeLosses(hide) {
  const losses = ['The photo of this hide'];
  if (hide.outlinePolygon) losses.push('Its traced outline and measured size');
  if (hide.colourL != null) losses.push('Its sampled colour');
  if (hide.dominantWavelengthMm != null) {
    losses.push(`Its scale measurement (${hide.dominantWavelengthMm.toFixed(2)}mm) — it would drop out of matching`);
  }
  const remaining = hide.remainingAreaPct ?? 100;
  if (remaining < 100) {
    losses.push(`The record that ${Math.round(100 - remaining)}% of it has already been cut`);
  }
  return losses;
}

async function openDeleteDialog(hideId) {
  const hide = hides.find((h) => h.id === hideId);
  if (!hide) return;

  deleteHideId = hideId;
  deleteSummary.innerHTML = `<strong>${escapeHtml(hide.label)}</strong> — ${escapeHtml(hide.species)}, ${hideSizeLabel(hide)}.`;
  deleteLosses.innerHTML = describeLosses(hide)
    .map((loss) => `<li>${escapeHtml(loss)}</li>`)
    .join('');
  deleteJobsWarning.hidden = true;
  deleteJobsWarning.textContent = '';
  deleteDialog.hidden = false;

  // Looked up only when the dialog opens, not on every page load -- it costs
  // a request, and it matters in the one moment before something becomes
  // irreversible. Jobs survive their hide being deleted, but they lose the
  // trace of what was cut from what.
  try {
    const sessions = await (await fetch('/sessions')).json();
    const linked = sessions.filter((session) => session.hideId === hideId);
    if (linked.length > 0 && deleteHideId === hideId) {
      const cut = linked.filter((session) => session.status === 'cut').length;
      deleteJobsWarning.textContent =
        `${linked.length} job${linked.length === 1 ? '' : 's'} reference${linked.length === 1 ? 's' : ''} this hide` +
        `${cut > 0 ? ` (${cut} already cut)` : ''}. They will keep working, but will no longer say which hide they came from.`;
      deleteJobsWarning.hidden = false;
    }
  } catch {
    // A failed lookup must not block the decision -- the dialog still states
    // everything else that is lost.
  }
}

