// The patch selector only appears once there's a photo to drag on, and it is
// rebuilt each time it's shown -- attachRegionSelect clears the container it
// is handed, so re-attaching on an empty one would leave nothing to click.
function refreshMatchingRegionSelect() {
  const wanted = forMatchingInput.checked && selectedPhoto !== null;
  matchingRegionWrapper.hidden = !wanted;
  if (!wanted) {
    matchingRegion = null;
    matchingRegionContainer.innerHTML = '';
    return;
  }
  attachRegionSelect(matchingRegionContainer, URL.createObjectURL(selectedPhoto), (result) => {
    matchingRegion = result;
  });
}

